// TestCRLFInput covers a file with Windows line endings: frontmatter must still
// be detected (and left verbatim), a colon intro must still be recognised, and
// the output must stay CRLF.
func TestCRLFInput(t *testing.T) {
	lf := "---\ntitle: T\ndescription: use <x> verbatim\n---\n\nFor example:\n\n\tomnictl get <id>\n"
	in := strings.ReplaceAll(lf, "\n", "\r\n")
	want := strings.ReplaceAll("---\ntitle: T\ndescription: use <x> verbatim\n---\n\nFor example:\n\n```\nomnictl get <id>\n```\n", "\n", "\r\n")
	once := string(normalizeBytes([]byte(in), false, true))
	if once != want {
		t.Errorf("CRLF input not normalized:\n got: %q\nwant: %q", once, want)
	}
	if twice := string(normalizeBytes([]byte(once), false, true)); once != twice {
		t.Errorf("CRLF pass not idempotent:\n once: %q\ntwice: %q", once, twice)
	}
	// The LF equivalent must produce the same content, modulo line endings.
	if got := string(normalizeBytes([]byte(lf), false, true)); got != strings.ReplaceAll(want, "\r\n", "\n") {
		t.Errorf("CRLF and LF results differ:\n got: %q\nwant: %q", got, strings.ReplaceAll(want, "\r\n", "\n"))
	}
}
