// Escaping must not double-escape its own output.
func TestEscapeInlineIdempotent(t *testing.T) {
	in := "use <machine-id> and {placeholder} and (cni {\"a\":\"b\"})\n"
	once := runEsc(t, in, false)
	twice := strings.Join(normalize(strings.Split(once, "\n"), false, true), "\n")
	if once != twice {
		t.Errorf("escape pass not idempotent:\n once: %q\ntwice: %q", once, twice)
	}
	if strings.Contains(once, "\\\\") {
		t.Errorf("double-escaped:\n got: %q", once)
	}
}

