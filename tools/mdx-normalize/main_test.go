// TestIdempotent runs a representative document twice through normalize and
// checks the second pass is a no-op, for both flag combinations.
func TestIdempotent(t *testing.T) {
	docs := []string{
		"To load completions:\n\n\tsource <(talosctl completion bash)\n",
		"- For each node:\n\n\t- Kernel logs.\n",
		"<table>\n  <tr>\n    <td>x</td>\n  </tr>\n</table>\n",
		"{/*\ngenerated\n*/}\n\nuse {\"<\"}id{\">\"} here\n",
	}
	for _, escape := range []bool{false, true} {
		for _, in := range docs {
			once := strings.Join(normalize(strings.Split(in, "\n"), false, escape), "\n")
			twice := strings.Join(normalize(strings.Split(once, "\n"), false, escape), "\n")
			if once != twice {
				t.Errorf("not idempotent (escape=%v):\n in:   %q\n once: %q\n twice:%q", escape, in, once, twice)
			}
		}
	}
}

// TestUnpairedBacktickStillEscapes covers CLI help with an odd number of
// backticks on a line: the stray backtick is not a code span, so escaping must
// continue past it rather than leaving a bare "<machine-id>" in the output.
func TestUnpairedBacktickStillEscapes(t *testing.T) {
	in := "use `omnictl and then <machine-id> is required\n"
	want := "use `omnictl and then \\<machine-id> is required\n"
	once := runEsc(t, in, false)
	if once != want {
		t.Errorf("unpaired backtick disabled escaping:\n got: %q\nwant: %q", once, want)
	}
	twice := strings.Join(normalize(strings.Split(once, "\n"), false, true), "\n")
	if once != twice {
		t.Errorf("unpaired-backtick escape not idempotent:\n once: %q\ntwice: %q", once, twice)
	}
	// A balanced pair still protects its contents.
	bal := "run `omnictl get <id>` for <machine-id>\n"
	wantBal := "run `omnictl get <id>` for \\<machine-id>\n"
	if got := runEsc(t, bal, false); got != wantBal {
		t.Errorf("balanced code span not respected:\n got: %q\nwant: %q", got, wantBal)
	}
}

