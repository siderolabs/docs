// TestHTMLTablePreserved is the key safety test: files with real HTML/JSX (the
// Talos config reference, schema-generated Omni pages) must pass through
// untouched when escaping is off — escaping would corrupt "<table>" into
// "\<table>".
func TestHTMLTablePreserved(t *testing.T) {
	in := "AddressConfig represents a network address configuration.\n\n<table>\n  <thead>\n    <tr>\n      <th>Field</th>\n    </tr>\n  </thead>\n</table>\n"
	if got := run(t, in, false); got != in {
		t.Errorf("HTML table altered with escaping off:\n got: %q\nwant: %q", got, in)
	}
}

// TestMDXExpressionsPreserved: with escaping off (the path used for HTML-bearing
// reference pages), {"<"} / {">"} JSX expressions and {/* */} comments must pass
// through untouched. This is the guarantee that protects the Talos reference.
func TestMDXExpressionsPreserved(t *testing.T) {
	in := "{/*\nThis file is automatically generated.\n*/}\n\nCreates an archive at {\"<\"}src-path{\">\"} now.\n"
	if got := run(t, in, false); got != in {
		t.Errorf("MDX expressions altered with escaping off:\n got: %q\nwant: %q", got, in)
	}
}

// TestEscapeInlineEscapesBraceExpressions locks in that --escape-inline escapes
// expression-looking prose too. These files are plain-markdown CLI help with no
// intentional JSX, so an unescaped "{" (e.g. a JSON default like {"cni":"x"})
// would break the MDX build.
func TestEscapeInlineEscapesBraceExpressions(t *testing.T) {
	in := "default is (cni {\"name\":\"flannel\"}) and path {/etc}\n"
	want := "default is (cni \\{\"name\":\"flannel\"}) and path \\{/etc}\n"
	if got := runEsc(t, in, false); got != want {
		t.Errorf("brace expression not escaped:\n got: %q\nwant: %q", got, want)
	}
}

