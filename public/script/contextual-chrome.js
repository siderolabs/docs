/*
 * Contextual navbar chrome.
 *
 * Things the design asks for that docs.json cannot express, because
 * Mintlify's navbar and search placeholder are global rather than per-page:
 *
 *   1. The search placeholder names the product being read, so search reads
 *      as scoped to that product rather than the whole site.
 *
 *   2. The product switcher is labelled "Product" rather than whichever product
 *      happens to be open, so it reads as a way to change product.
 *
 *   3. The version switcher is hidden outside a versioned product. Mintlify
 *      already hides it on products that have no versions; the gap is the
 *      landing page, where it falls back to the first product's versions and
 *      offers Talos releases to someone who is not reading Talos.
 *
 *   4. The navbar button belongs to the product being read. Each product
 *      declares its `cta` in its nav file; a product without one shows no
 *      button. Rather than inserting a button of its own, this relabels or
 *      hides the navbar.primary one Mintlify already renders, so it keeps
 *      Mintlify's styling in both themes. If this script fails to load, the
 *      site falls back to navbar.primary on every page.
 *
 *   5. Search opens filtered to the product being read. Mintlify's search
 *      modal has a product filter but opens with it unset, so the first time
 *      the modal opens on a page this picks the open product in that filter.
 *      Reopening on the same page keeps whatever the reader chose since, so
 *      clearing the filter to search every product sticks.
 *
 * Mintlify sets data-current-path on <html> and keeps it up to date across
 * client-side navigation, which is what makes this possible without a reload.
 */
(function () {
  "use strict";

  // Everything the navbar needs to know about a product, generated by
  // tools/docs-gen into script/product-nav.js and keyed by the first path
  // segment of that product's pages.
  //
  // Deliberately not a list maintained here: this used to be hand-written, and
  // a product missing from it silently lost its version switcher and its
  // search placeholder.
  function productInfo(product) {
    var map = window.sideroProducts;
    if (!map || !product) return null;
    return map[product] || null;
  }

  var DEFAULT_SEARCH_TEXT = "Search...";
  var PRODUCT_SWITCHER_LABEL = "Product";

  // A version label as the switcher renders it, e.g. "v1.14".
  var VERSION_LABEL = /^v\d+\.\d+/;

  function headerButtons() {
    return Array.prototype.slice.call(document.querySelectorAll("header button"));
  }

  // Replaces a button's visible text without disturbing any icon beside it.
  function setButtonLabel(button, text) {
    var changed = false;
    Array.prototype.forEach.call(button.childNodes, function (node) {
      if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
        if (node.textContent !== text) {
          node.textContent = text;
          changed = true;
        }
      }
    });

    if (changed) return;

    // Some builds wrap the label in a span rather than a bare text node.
    var span = button.querySelector("span:not([class*='line-clamp'])") || button.querySelector("span");
    if (span && span.textContent.trim() && span.textContent !== text) {
      span.textContent = text;
    }
  }

  function applyProductSwitcher(product) {
    var info = productInfo(product);
    var current = info ? info.name : null;

    headerButtons().forEach(function (button) {
      var text = button.textContent.trim();

      // The switcher shows the open product's name, or the label already set
      // on a previous pass.
      var isSwitcher =
        text === PRODUCT_SWITCHER_LABEL ||
        (current && text === current) ||
        isKnownProductName(text);

      if (!isSwitcher) return;

      setButtonLabel(button, PRODUCT_SWITCHER_LABEL);

      // Mintlify puts the open product's icon in the trigger. Once the label
      // reads "Product" rather than the product's name, that icon is claiming
      // something the label no longer says, so it goes.
      Array.prototype.forEach.call(button.querySelectorAll("img, svg"), function (mark) {
        // The chevron is the button's last element child and is what tells a
        // reader this opens a menu, so only the product mark before the label
        // is hidden.
        if (mark === button.lastElementChild) return;
        mark.style.display = "none";
      });
    });
  }

  // Whether a label is a nav node's own name, and so the switcher rather than
  // some other header button. Hidden nodes like the changelog are in the
  // generated map too, so nothing needs listing here by hand.
  function isKnownProductName(text) {
    var map = window.sideroProducts;
    if (!map) return false;
    for (var key in map) {
      if (Object.prototype.hasOwnProperty.call(map, key) && map[key].name === text) {
        return true;
      }
    }
    return false;
  }

  function applyVersionSwitcher(product) {
    // Only products that actually carry versions should offer the switcher.
    // Mintlify handles that for product pages already; this covers the landing
    // page, where it would otherwise show the first product's versions.
    //
    // Keyed on the generated `versioned` flag rather than on the product merely
    // being known: gating on presence in a hand-written list meant any product
    // missing from it had its switcher hidden even when it had versions.
    var info = productInfo(product);
    var showVersions = Boolean(info && info.versioned);

    headerButtons().forEach(function (button) {
      if (!VERSION_LABEL.test(button.textContent.trim())) return;

      var wrapper = button.parentElement || button;
      if (showVersions) {
        wrapper.style.removeProperty("display");
      } else {
        wrapper.style.display = "none";
      }
    });
  }

  function productFromPath(path) {
    var segments = (path || "/").split("/").filter(Boolean);
    return segments.length ? segments[0] : null;
  }

  // The navbar.primary button, desktop and mobile copies. Found by the
  // default href on first sight, then marked, since a relabelled button may
  // no longer carry that href. Scoped to #navbar because page content links
  // the same signup URL.
  function navbarCTAs() {
    var fallback = window.sideroNavbarCTA;
    var navbar = document.getElementById("navbar");
    if (!navbar || !fallback) return [];

    Array.prototype.forEach.call(navbar.querySelectorAll("a[href]"), function (link) {
      if (link.getAttribute("href") === fallback.href) {
        link.setAttribute("data-sidero-cta", "");
      }
    });
    return Array.prototype.slice.call(navbar.querySelectorAll("a[data-sidero-cta]"));
  }

  // Replaces the deepest text in a link without touching the chevron icon.
  function setLinkLabel(link, text) {
    var walker = document.createTreeWalker(link, NodeFilter.SHOW_TEXT);
    var node;
    while ((node = walker.nextNode())) {
      if (node.textContent.trim()) {
        if (node.textContent !== text) node.textContent = text;
        return;
      }
    }
  }

  function applyCTA(product) {
    var info = productInfo(product);
    var cta = info && info.cta;

    navbarCTAs().forEach(function (link) {
      var item = link.closest("li") || link;
      if (!cta) {
        item.style.display = "none";
        return;
      }
      item.style.removeProperty("display");
      if (link.getAttribute("href") !== cta.href) link.setAttribute("href", cta.href);
      setLinkLabel(link, cta.label);
    });
  }

  function applySearchPlaceholder(product) {
    var entry = document.getElementById("search-bar-entry");
    if (!entry) return;

    var label = document.querySelector("#search-bar-entry .truncate");
    if (!label) return;

    var info = productInfo(product);
    var text = info && info.name ? "Search the " + info.name + " documentation" : DEFAULT_SEARCH_TEXT;

    if (label.textContent !== text) {
      label.textContent = text;
    }
  }

  // The path the search filter was last preselected for. Mintlify keeps the
  // modal mounted between opens and remembers its filter, so preselecting once
  // per page is what leaves a reader's own choice alone on reopening.
  var searchFilterPath = null;

  // The modal whose data-open attribute is being watched, and the observer
  // doing it. Opening the modal changes only that attribute, which the
  // childList observer in start() does not see.
  var watchedSearchModal = null;
  var searchModalObserver = null;

  function watchSearchModal(modal) {
    if (modal === watchedSearchModal) return;
    if (searchModalObserver) searchModalObserver.disconnect();
    watchedSearchModal = modal;
    searchModalObserver = new MutationObserver(scheduleApply);
    searchModalObserver.observe(modal, { attributes: true, attributeFilter: ["data-open"] });
  }

  function searchFilterMenu() {
    return document.querySelector('[data-component-part="search-filter-content"]');
  }

  // Polls until test() returns something truthy or timeoutMs passes, then
  // calls done() with the last result.
  function waitFor(test, done, timeoutMs) {
    var started = Date.now();
    (function poll() {
      var result = test();
      if (result || Date.now() - started >= timeoutMs) {
        done(result);
        return;
      }
      window.setTimeout(poll, 25);
    })();
  }

  function applySearchFilter(product, path) {
    var modal = document.querySelector('[data-component-part="search-modal"]');
    if (!modal) return;
    watchSearchModal(modal);
    if (!modal.hasAttribute("data-open") || searchFilterPath === path) return;

    var info = productInfo(product);
    var trigger = modal.querySelector('[data-component-part="search-filter-trigger"]');
    if (!info || !trigger) return;

    searchFilterPath = path;
    if (trigger.textContent.trim() === info.name) return;

    // The filter is a Base UI menu, so choosing an option means opening it and
    // clicking the item. The menu stays hidden and inert meanwhile (see
    // style.css), including through its close animation, so the reader never
    // sees it open.
    var root = document.documentElement;
    root.setAttribute("data-sidero-search-filter", "");
    trigger.click();

    waitFor(
      function () {
        var menu = searchFilterMenu();
        if (!menu) return null;
        return Array.prototype.find.call(menu.querySelectorAll('[role="menuitem"]'), function (option) {
          return option.textContent.trim() === info.name;
        });
      },
      function (item) {
        if (item) {
          item.click();
        } else if (trigger.getAttribute("aria-expanded") === "true") {
          // The product is missing from the filter: close the menu untouched.
          trigger.click();
        }

        // Closing the menu hands focus back to its trigger. Return it to the
        // search input so the reader can type straight away.
        waitFor(
          function () {
            return trigger.getAttribute("aria-expanded") !== "true";
          },
          function () {
            var input = document.getElementById("search-input");
            if (input && modal.hasAttribute("data-open")) input.focus();
          },
          500
        );

        waitFor(
          function () {
            return !searchFilterMenu();
          },
          function () {
            root.removeAttribute("data-sidero-search-filter");
          },
          2000
        );
      },
      500
    );
  }

  function apply() {
    var path = document.documentElement.getAttribute("data-current-path") || window.location.pathname;
    var product = productFromPath(path);
    applyCTA(product);
    applySearchPlaceholder(product);
    applyProductSwitcher(product);
    applyVersionSwitcher(product);
    applySearchFilter(product, path);
  }

  var pending = null;
  function scheduleApply() {
    if (pending) return;
    pending = window.setTimeout(function () {
      pending = null;
      apply();
    }, 50);
  }

  function start() {
    apply();

    // Route changes: Mintlify updates this attribute instead of reloading.
    new MutationObserver(scheduleApply).observe(document.documentElement, {
      attributes: true,
      attributeFilter: ["data-current-path"]
    });

    // Re-renders: React can replace the navbar without the path changing, which
    // would otherwise restore the default button and placeholder.
    new MutationObserver(scheduleApply).observe(document.body, {
      childList: true,
      subtree: true
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start);
  } else {
    start();
  }
})();
